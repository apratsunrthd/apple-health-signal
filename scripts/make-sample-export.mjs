#!/usr/bin/env node
// Write the app's built-in fictional sample person as a real Apple Health export,
// so people can try the upload path without their own data.
//   node scripts/make-sample-export.mjs [outDir]   (default: sample/apple_health_export)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createAppInstance } from '../tests/harness.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'sample', 'apple_health_export'));

function hkDate(t) {
  const d = new Date(t), p = n => String(n).padStart(2, '0');
  const off = -d.getTimezoneOffset(), sign = off >= 0 ? '+' : '-', a = Math.abs(off);
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())} ${sign}${p(Math.floor(a / 60))}${p(a % 60)}`;
}
const esc = v => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
function rec(type, unit, t, value, end, source = 'Sample Watch') {
  return ` <Record type="HKQuantityTypeIdentifier${type}" sourceName="${source}" unit="${unit}" startDate="${hkDate(t)}" endDate="${hkDate(end || t)}" value="${value}"/>`;
}

const { app } = await createAppInstance();
app.genSampleData();
const h = app.state.sources.health;
const lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- Fictional sample person generated by scripts/make-sample-export.mjs -->', '<HealthData locale="en_US">', ` <ExportDate value="${hkDate(Date.now())}"/>`];

h.glucoseParsed.forEach(r => lines.push(rec('BloodGlucose', 'mg/dL', r.t, r.v, null, 'Sample CGM')));
h.heartRateParsed.forEach(r => lines.push(rec('HeartRate', 'count/min', r.t, r.v)));
h.restingHrParsed.forEach(r => lines.push(rec('RestingHeartRate', 'count/min', r.t, r.v)));
h.hrvParsed.forEach(r => lines.push(rec('HeartRateVariabilitySDNN', 'ms', r.t, r.v)));
h.vo2MaxParsed.forEach(r => lines.push(rec('VO2Max', 'mL/min·kg', r.t, r.v)));
h.weightParsed.forEach(r => lines.push(rec('BodyMass', 'lb', r.t, r.v, null, 'Sample Scale')));
h.bmiParsed.forEach(r => lines.push(rec('BodyMassIndex', 'count', r.t, r.v, null, 'Sample Scale')));
h.bodyFatParsed.forEach(r => lines.push(rec('BodyFatPercentage', '%', r.t, (r.v / 100).toFixed(3), null, 'Sample Scale')));
h.leanMassParsed.forEach(r => lines.push(rec('LeanBodyMass', 'lb', r.t, r.v, null, 'Sample Scale')));
h.sleepParsed.forEach(r => lines.push(` <Record type="HKCategoryTypeIdentifierSleepAnalysis" sourceName="Sample Watch" startDate="${hkDate(r.t)}" endDate="${hkDate(r.endT)}" value="HKCategoryValueSleepAnalysisAsleepCore"/>`));
h.energyParsed.forEach(e => {
  const [y, m, d] = e.day.split('-').map(Number), noon = new Date(y, m - 1, d, 12).getTime();
  lines.push(rec('ActiveEnergyBurned', 'Cal', noon, e.active), rec('BasalEnergyBurned', 'Cal', noon, e.basal));
});
h.eventsParsed.forEach(e => {
  if (e.type === 'exercise') {
    lines.push(` <Workout workoutActivityType="HKWorkoutActivityType${e.label}" duration="${e.durationMin}" durationUnit="min" sourceName="Sample Watch" startDate="${hkDate(e.t)}" endDate="${hkDate(e.t + e.durationMin * 60000)}"/>`);
  } else if (e.type === 'meal') {
    lines.push(` <Record type="HKQuantityTypeIdentifierDietaryEnergyConsumed" sourceName="Sample Food Log" unit="Cal" startDate="${hkDate(e.t)}" endDate="${hkDate(e.t)}" value="${e.calories}">`,
      `  <MetadataEntry key="HKFoodType" value="${esc(e.label)}"/>`, ' </Record>');
    [['DietaryProtein', e.protein], ['DietaryCarbohydrates', e.carbs], ['DietaryFatTotal', e.fat]].forEach(([type, v]) => {
      if (v != null) lines.push(rec(type, 'g', e.t, v, null, 'Sample Food Log'));
    });
  }
});
lines.push('</HealthData>', '');

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'clinical-records'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'export.xml'), lines.join('\n'));
app.state.clinicalLabs.forEach((lab, i) => {
  const range = {};
  if (lab.refLow != null) range.low = { value: lab.refLow, unit: lab.unit };
  if (lab.refHigh != null) range.high = { value: lab.refHigh, unit: lab.unit };
  const obs = {
    resourceType: 'Observation', id: `sample-${i + 1}`, status: 'final',
    code: { text: lab.name }, effectiveDateTime: new Date(lab.t).toISOString(),
    valueQuantity: { value: lab.value, unit: lab.unit }, referenceRange: [range]
  };
  fs.writeFileSync(path.join(OUT, 'clinical-records', `Observation-sample-${i + 1}.json`), JSON.stringify(obs, null, 2) + '\n');
});
console.log(`Wrote ${lines.length.toLocaleString()} lines and ${app.state.clinicalLabs.length} lab files to ${path.relative(ROOT, OUT) || OUT}`);
